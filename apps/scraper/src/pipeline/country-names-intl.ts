/**
 * Country names in French, Spanish and Portuguese (Oct 21, 2026).
 *
 * The reader takes feeds in four languages (en, es, pt, fr), but the
 * place-finder knew countries by their English names only, so a French
 * headline about "l'Algérie", "le Maroc" or "le Sénégal" named no country:
 * a probe of 119 such names found 91 that matched nothing ("Égypte",
 * "États-Unis", "Allemagne", "España", "México", "Moçambique"...), and
 * LesEco.ma's 20 items placed none (round 5's helpers). Feeds in those
 * languages get no home pin, so their stories stayed off the map.
 *
 * Each pattern matches a whole word in any letters (\p{L}: "Égypte" starts
 * with a letter \b doesn't know) and ignores case. Only the spellings that
 * differ from the English ones are here: "Sudan", "Niger", "Mexico" or
 * "Albania" keep their English patterns, which know "South Sudan", the
 * Niger Delta and New Mexico. Left out on purpose:
 * names that are everyday words or names in one of the four languages
 * ("Gana" is "wins" in Spanish, "Catar" is "to taste", "Chili" a dish,
 * "Equador"/"Équateur" the equator, "Mauricio" and "Francia" first names,
 * "camarões" prawns, "lingua franca", "suède" leather), and "congolais",
 * which fits both Congos. Bare "Maurice" (mostly a first name) and a
 * Brazzaville outlet's bare "Congo" are read at home only (geo.ts,
 * withHomeNames).
 */

